def categorize(probs, thresholds):
    """구간별 확률 -> 단계 0~4.

    ★ 단조성 보정은 **호출하는 쪽**에서 이미 끝났다고 가정한다
      (P[i] = min(P[i], P[i-1]), 낮은 문턱부터). 빠뜨리면 화소의 32.6% 에서
      P(>=10) > P(>=3) 같은 모순된 확률이 화면에 뜬다.
    """
    lv = 0
    for i, b in enumerate(BINS):
        if probs[b] >= thresholds[b]:
            lv = i + 1
    return lv
